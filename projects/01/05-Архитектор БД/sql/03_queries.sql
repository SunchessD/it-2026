-- Регистрация нового пользователя
INSERT INTO Пользователь (Имя, Email, ХешПароля, СтатусАктивации, РольПлатформы)
VALUES ('Новый Пользователь', 'new@example.com', 'hashed_password', 'Неактивна', 'пользователь');

-- Авторизация (проверка данных)
SELECT IdПользователя, Имя, Email, РольПлатформы, СтатусАктивации
FROM Пользователь
WHERE Email = 'maria@example.com' AND СтатусАктивации = 'Активна';

-- Активация аккаунта
UPDATE Пользователь
SET СтатусАктивации = 'Активна'
WHERE IdПользователя = 4;

-- Блокировка пользователя
UPDATE Пользователь
SET ПризнакБлокировки = True
WHERE IdПользователя = 3;


-- ============================================================
-- МОДЕЛИ И ДОСТУП
-- ============================================================

-- Получить все модели пользователя (свои + доступные)
SELECT m.IdМодели, m.Название, m.ДатаИзменения, m.ТипДоступа,
       IIf(m.IdВладельца = 2, 'владелец', d.УровеньДоступа) AS МояРоль
FROM Модель m
LEFT JOIN ДоступКМодели d ON m.IdМодели = d.IdМодели AND d.IdПользователя = 2
WHERE m.IdВладельца = 2 OR d.IdПользователя = 2
ORDER BY m.ДатаИзменения DESC;

-- Создать новую модель
INSERT INTO Модель (IdВладельца, Название, Описание, ТипДоступа)
VALUES (2, 'Новая модель', 'Описание новой модели', 'приватная');

-- Переименовать модель
UPDATE Модель
SET Название = 'Модель очереди v2', ДатаИзменения = Now()
WHERE IdМодели = 1 AND IdВладельца = 2;

-- Выдать доступ к модели
INSERT INTO ДоступКМодели (IdПользователя, IdМодели, УровеньДоступа)
VALUES (3, 1, 'просмотр');

-- Получить список участников модели
SELECT u.Имя, u.Email, d.УровеньДоступа, d.ДатаПредоставления
FROM ДоступКМодели d
INNER JOIN Пользователь u ON d.IdПользователя = u.IdПользователя
WHERE d.IdМодели = 2;


-- ============================================================
-- СОСТОЯНИЯ И ВЕРСИИ
-- ============================================================

-- Получить текущее состояние модели
SELECT IdСостояния, ДатаСоздания
FROM СостояниеМодели
WHERE IdМодели = 1 AND ЯвляетсяТекущим = True;

-- Создать версию модели
INSERT INTO ВерсияМодели (IdМодели, IdСостояния, Название, ПризнакНеизменяемости)
VALUES (1, 1, 'v1.1 — после доработки', True);

-- Список версий модели
SELECT IdВерсии, Название, ДатаФиксации, ПризнакНеизменяемости
FROM ВерсияМодели
WHERE IdМодели = 1
ORDER BY ДатаФиксации DESC;


-- ============================================================
-- СТРУКТУРА МОДЕЛИ
-- ============================================================

-- Получить все элементы текущего состояния модели
SELECT e.IdЭлемента, e.Название, e.ТипЭлемента, e.ПозицияX, e.ПозицияY
FROM ЭлементМодели e
INNER JOIN СостояниеМодели s ON e.IdСостояния = s.IdСостояния
WHERE s.IdМодели = 1 AND s.ЯвляетсяТекущим = True;

-- Получить связи модели
SELECT sv.IdСвязи, 
       e1.Название AS Источник, 
       e2.Название AS Цель, 
       sv.ТипВзаимодействия
FROM ((Связь sv
INNER JOIN ЭлементМодели e1 ON sv.IdЭлементаИсточника = e1.IdЭлемента)
INNER JOIN ЭлементМодели e2 ON sv.IdЭлементаЦели = e2.IdЭлемента)
INNER JOIN СостояниеМодели s ON sv.IdСостояния = s.IdСостояния
WHERE s.IdМодели = 1 AND s.ЯвляетсяТекущим = True;

-- Параметры модели
SELECT Название, ТипЗначения, Значение, ИзменяемостьПриЗапуске
FROM Параметр
WHERE IdСостояния = 1;

-- Программная логика модели
SELECT ТекстPython, ДатаИзменения
FROM ПрограммнаяЛогика
WHERE IdСостояния = 1;


-- ============================================================
-- СИМУЛЯЦИЯ
-- ============================================================

-- Запустить симуляцию (создать запись результата)
INSERT INTO РезультатСимуляции (IdМодели, IdВерсии, ПараметрыЗапуска, Статус)
VALUES (1, 1, 'интенсивность=5.0; время=2.5', 'выполняется');

-- Получить результаты симуляций модели
SELECT IdРезультата, ДатаЗапуска, Статус, ПараметрыЗапуска
FROM РезультатСимуляции
WHERE IdМодели = 1
ORDER BY ДатаЗапуска DESC;

-- Обновить статус симуляции
UPDATE РезультатСимуляции
SET Статус = 'завершена', 
    ДанныеРезультата = 'Среднее время ожидания: 4.2'
WHERE IdРезультата = 1;


-- ============================================================
-- СТАТИСТИКА И ОТЧЁТЫ
-- ============================================================

-- Количество моделей у пользователя
SELECT u.Имя, COUNT(m.IdМодели) AS КоличествоМоделей
FROM Пользователь u
LEFT JOIN Модель m ON u.IdПользователя = m.IdВладельца
WHERE u.IdПользователя = 2
GROUP BY u.Имя;

-- Статистика по типам элементов в модели
SELECT e.ТипЭлемента, COUNT(*) AS Количество
FROM ЭлементМодели e
INNER JOIN СостояниеМодели s ON e.IdСостояния = s.IdСостояния
WHERE s.IdМодели = 1 AND s.ЯвляетсяТекущим = True
GROUP BY e.ТипЭлемента;

-- Количество версий по моделям
SELECT m.Название, COUNT(v.IdВерсии) AS КоличествоВерсий
FROM Модель m
LEFT JOIN ВерсияМодели v ON m.IdМодели = v.IdМодели
GROUP BY m.Название
ORDER BY COUNT(v.IdВерсии) DESC;

-- Модели, к которым пользователю дан доступ
SELECT m.Название, d.УровеньДоступа, u.Имя AS Владелец
FROM (ДоступКМодели d
INNER JOIN Модель m ON d.IdМодели = m.IdМодели)
INNER JOIN Пользователь u ON m.IdВладельца = u.IdПользователя
WHERE d.IdПользователя = 3;
