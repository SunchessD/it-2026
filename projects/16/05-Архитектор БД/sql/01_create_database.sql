-- Веб-сервис учёта и анализа личных расходов. PostgreSQL 17.
-- Запускать в отдельной пустой БД, например expenses_design.
-- Скрипт создаёт таблицы внутри БД, но не саму БД.
-- auth_user и django_session включены для самостоятельной проверки схемы.
-- В приложении их и остальные служебные таблицы создают миграции Django.

BEGIN;

CREATE TABLE auth_user (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password     varchar(128) NOT NULL,
    last_login   timestamptz,
    is_superuser boolean NOT NULL,
    username     varchar(150) NOT NULL UNIQUE,
    first_name   varchar(150) NOT NULL,
    last_name    varchar(150) NOT NULL,
    email        varchar(254) NOT NULL,
    is_staff     boolean NOT NULL,
    is_active    boolean NOT NULL,
    date_joined  timestamptz NOT NULL
);

CREATE TABLE finance_revision (
    user_id  integer PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 0,
    CONSTRAINT fk_revision_user FOREIGN KEY (user_id)
        REFERENCES auth_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_revision_nonnegative CHECK (revision >= 0)
);

CREATE TABLE finance_category (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL,
    name        varchar(50) NOT NULL,
    is_archived boolean NOT NULL DEFAULT false,
    CONSTRAINT fk_category_user FOREIGN KEY (user_id)
        REFERENCES auth_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_category_name CHECK (
        name = btrim(name) AND char_length(name) > 0
    ),
    CONSTRAINT uq_category_id_owner UNIQUE (id, user_id)
);

-- Уникальность распространяется и на архивные категории.
CREATE UNIQUE INDEX uq_category_owner_name
    ON finance_category (user_id, lower(name));

CREATE TABLE finance_expense (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer NOT NULL,
    category_id  bigint NOT NULL,
    amount_minor bigint NOT NULL,
    expense_date date NOT NULL,
    comment      varchar(255) NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_expense_user FOREIGN KEY (user_id)
        REFERENCES auth_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_expense_category_owner FOREIGN KEY (category_id, user_id)
        REFERENCES finance_category (id, user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_expense_amount CHECK (
        amount_minor BETWEEN 1 AND 99999999999
    )
);

CREATE INDEX ix_expense_owner_date
    ON finance_expense (user_id, expense_date DESC, id DESC);
CREATE INDEX ix_expense_owner_category_date
    ON finance_expense (user_id, category_id, expense_date DESC);

CREATE TABLE django_session (
    session_key  varchar(40) PRIMARY KEY,
    session_data text NOT NULL,
    expire_date  timestamptz NOT NULL
);

CREATE INDEX ix_session_expire_date ON django_session (expire_date);

COMMENT ON COLUMN finance_expense.amount_minor IS
    'Целые копейки; 8000 соответствует 80,00 рубля';
COMMENT ON COLUMN finance_expense.expense_date IS
    'Календарная дата расхода, без часового пояса';
COMMENT ON COLUMN finance_expense.updated_at IS
    'При редактировании значение обновляет приложение';
COMMENT ON COLUMN finance_revision.revision IS
    'Увеличивается приложением в одной транзакции с изменением данных';
COMMENT ON TABLE django_session IS
    'Сессии Django. Отдельного внешнего ключа на auth_user нет';

COMMIT;
