DO $$
DECLARE r record; v_max bigint;
BEGIN
    FOR r IN SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'stylestore' AND is_identity = 'YES' LOOP
        EXECUTE format('SELECT COALESCE(MAX(%I), 0) FROM stylestore.%I', r.column_name, r.table_name) INTO v_max;
        PERFORM setval(pg_get_serial_sequence(format('stylestore.%I', r.table_name), r.column_name), v_max + 1, false);
    END LOOP;
END;
$$;

