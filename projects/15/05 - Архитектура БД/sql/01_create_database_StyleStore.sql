CREATE INDEX "ix_Товар_2" ON "Товар" ("id_категории", "опубликован", "цена");

CREATE INDEX "ix_поиск_товара" ON "Товар" USING GIN (to_tsvector('russian', "название" || ' ' || "описание")) ;

CREATE TABLE "Вариант_товара" (
  "id_варианта" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_товара" integer NOT NULL REFERENCES "Товар"("id_товара"),
  "цвет" varchar(100) NOT NULL,
  "размер" varchar(16) NOT NULL,
  "доступный_остаток" integer NOT NULL DEFAULT 0,
  UNIQUE ("id_товара", "цвет", "размер"),
  CHECK ("доступный_остаток" >= 0)
);

CREATE TABLE "Корзина" (
  "id_корзины" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_покупателя" integer UNIQUE REFERENCES "Покупатель"("id_пользователя"),
  "ключ_сессии" uuid NOT NULL UNIQUE,
  "дата_обновления" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "Позиция_корзины" (
  "id_позиции_корзины" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_корзины" integer NOT NULL REFERENCES "Корзина"("id_корзины"),
  "id_варианта" integer NOT NULL REFERENCES "Вариант_товара"("id_варианта"),
  "количество" integer NOT NULL DEFAULT 1,
  UNIQUE ("id_корзины", "id_варианта"),
  CHECK ("количество" > 0)
);

CREATE TABLE "Избранное" (
  "id_избранного" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_пользователя" integer NOT NULL UNIQUE REFERENCES "Пользователь"("id_пользователя"),
  "дата_обновления" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "Позиция_избранного" (
