CREATE FUNCTION нормализовать_email()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW."email" := lower(btrim(NEW."email"));
    RETURN NEW;
END;
$$;

CREATE TRIGGER нормализация_email
BEFORE INSERT OR UPDATE OF "email" ON "Пользователь"
FOR EACH ROW EXECUTE FUNCTION нормализовать_email();

CREATE FUNCTION обновить_дату_списка()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'Позиция_корзины' THEN
        IF TG_OP <> 'INSERT' THEN
            UPDATE "Корзина" SET "дата_обновления" = CURRENT_TIMESTAMP
            WHERE "id_корзины" = OLD."id_корзины";
        END IF;
        IF TG_OP <> 'DELETE' THEN
            UPDATE "Корзина" SET "дата_обновления" = CURRENT_TIMESTAMP
            WHERE "id_корзины" = NEW."id_корзины";
        END IF;
    ELSE
        IF TG_OP <> 'INSERT' THEN
            UPDATE "Избранное" SET "дата_обновления" = CURRENT_TIMESTAMP
            WHERE "id_избранного" = OLD."id_избранного";
        END IF;
        IF TG_OP <> 'DELETE' THEN
            UPDATE "Избранное" SET "дата_обновления" = CURRENT_TIMESTAMP
            WHERE "id_избранного" = NEW."id_избранного";
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER дата_корзины
AFTER INSERT OR UPDATE OR DELETE ON "Позиция_корзины"
FOR EACH ROW EXECUTE FUNCTION обновить_дату_списка();

CREATE TRIGGER дата_избранного
AFTER INSERT OR UPDATE OR DELETE ON "Позиция_избранного"
FOR EACH ROW EXECUTE FUNCTION обновить_дату_списка();

CREATE FUNCTION добавить_в_корзину(p_корзина integer, p_вариант integer, p_количество integer)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_остаток integer;
    v_количество integer;
BEGIN
    IF p_количество IS NULL OR p_количество <= 0 THEN
        RAISE EXCEPTION 'Количество должно быть положительным';
    END IF;
    PERFORM 1 FROM "Корзина" WHERE "id_корзины" = p_корзина FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Корзина не найдена'; END IF;

    SELECT v."доступный_остаток" INTO v_остаток
    FROM "Вариант_товара" v JOIN "Товар" t USING ("id_товара")
    WHERE v."id_варианта" = p_вариант AND t."опубликован"
    FOR UPDATE OF v, t;
    IF NOT FOUND THEN RAISE EXCEPTION 'Товар недоступен'; END IF;

    SELECT COALESCE(SUM("количество"), 0) INTO v_количество
    FROM "Позиция_корзины"
    WHERE "id_корзины" = p_корзина AND "id_варианта" = p_вариант;
    IF p_количество > v_остаток - v_количество THEN
        RAISE EXCEPTION 'Недостаточный остаток товара';
    END IF;

    INSERT INTO "Позиция_корзины" ("id_корзины", "id_варианта", "количество")
    VALUES (p_корзина, p_вариант, p_количество)
    ON CONFLICT ("id_корзины", "id_варианта")
    DO UPDATE SET "количество" = "Позиция_корзины"."количество" + EXCLUDED."количество";
END;
$$;

CREATE FUNCTION оформить_заказ(
    p_покупатель integer,
    p_номер varchar,
    p_доставка delivery_method,
    p_город varchar,
    p_адрес varchar,
    p_имя varchar,
    p_телефон varchar,
    p_email varchar,
    p_оплата payment_method,
    p_операция varchar DEFAULT NULL
)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_корзина integer;
    v_заказ integer;
    v_владелец integer;
    v_товары numeric(12,2);
    v_доставка numeric(12,2);
BEGIN
    IF p_номер IS NULL OR btrim(p_номер) = ''
       OR p_город IS NULL OR btrim(p_город) = ''
       OR p_адрес IS NULL OR btrim(p_адрес) = ''
       OR p_имя IS NULL OR btrim(p_имя) = ''
       OR p_телефон IS NULL OR btrim(p_телефон) = ''
       OR p_email IS NULL OR position('@' IN p_email) < 2
       OR p_доставка IS NULL OR p_оплата IS NULL THEN
        RAISE EXCEPTION 'Некорректные данные получателя или заказа';
    END IF;
    IF p_оплата = 'card' AND (p_операция IS NULL OR btrim(p_операция) = '') THEN
        RAISE EXCEPTION 'Отсутствует подтверждение оплаты';
    END IF;
    IF p_оплата = 'receipt' AND p_операция IS NOT NULL THEN
        RAISE EXCEPTION 'При получении идентификатор платёжного сервиса не требуется';
    END IF;
    PERFORM 1 FROM "Покупатель" b JOIN "Пользователь" u USING ("id_пользователя")
    WHERE b."id_пользователя" = p_покупатель AND u."статус_аккаунта" = 'active';
    IF NOT FOUND THEN RAISE EXCEPTION 'Покупатель не активирован'; END IF;

    SELECT "id_корзины" INTO v_корзина FROM "Корзина"
    WHERE "id_покупателя" = p_покупатель FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Корзина покупателя не найдена'; END IF;

    SELECT "id_заказа", "id_покупателя" INTO v_заказ, v_владелец
    FROM "Заказ" WHERE "номер" = p_номер;
    IF FOUND THEN
        IF v_владелец <> p_покупатель OR NOT EXISTS (
            SELECT 1 FROM "Платёж" WHERE "id_заказа" = v_заказ AND "способ" = p_оплата
            AND "id_операции" IS NOT DISTINCT FROM p_операция
        ) THEN RAISE EXCEPTION 'Номер заказа уже используется'; END IF;
        RETURN v_заказ;
    END IF;

    PERFORM 1 FROM "Позиция_корзины"
    WHERE "id_корзины" = v_корзина ORDER BY "id_варианта" FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Корзина пуста'; END IF;

    PERFORM 1
    FROM "Вариант_товара" v
    JOIN "Позиция_корзины" c USING ("id_варианта")
    JOIN "Товар" t ON t."id_товара" = v."id_товара"
    WHERE c."id_корзины" = v_корзина
    ORDER BY v."id_варианта" FOR UPDATE OF v, t;

    IF EXISTS (
        SELECT 1 FROM "Позиция_корзины" c
        JOIN "Вариант_товара" v USING ("id_варианта")
        JOIN "Товар" t USING ("id_товара")
        WHERE c."id_корзины" = v_корзина
          AND (NOT t."опубликован" OR c."количество" > v."доступный_остаток")
    ) THEN RAISE EXCEPTION 'Товар скрыт или отсутствует в нужном количестве'; END IF;

    SELECT SUM(t."цена" * c."количество") INTO v_товары
    FROM "Позиция_корзины" c JOIN "Вариант_товара" v USING ("id_варианта")
    JOIN "Товар" t USING ("id_товара") WHERE c."id_корзины" = v_корзина;
    v_доставка := CASE WHEN p_доставка = 'courier' AND v_товары < 7990 THEN 390 ELSE 0 END;

    INSERT INTO "Заказ" ("id_покупателя", "номер", "итоговая_сумма", "имя_получателя", "телефон_получателя", "email_получателя")
    VALUES (p_покупатель, p_номер, v_товары + v_доставка, btrim(p_имя), btrim(p_телефон), lower(btrim(p_email)))
    RETURNING "id_заказа" INTO v_заказ;

    INSERT INTO "Доставка" ("id_заказа", "способ", "город", "адрес", "стоимость")
    VALUES (v_заказ, p_доставка, p_город, p_адрес, v_доставка);

    WITH позиции AS (
        INSERT INTO "Позиция_заказа" ("id_заказа", "id_варианта", "название_модели", "цвет", "размер", "цена_на_момент_заказа", "количество")
        SELECT v_заказ, v."id_варианта", t."название", v."цвет", v."размер", t."цена", c."количество"
        FROM "Позиция_корзины" c JOIN "Вариант_товара" v USING ("id_варианта")
        JOIN "Товар" t USING ("id_товара") WHERE c."id_корзины" = v_корзина
        RETURNING "id_позиции_заказа", "количество"
    )
    INSERT INTO "Резерв" ("id_позиции_заказа", "количество")
    SELECT "id_позиции_заказа", "количество" FROM позиции;

    UPDATE "Вариант_товара" v
    SET "доступный_остаток" = v."доступный_остаток" - c."количество"
    FROM "Позиция_корзины" c
    WHERE c."id_корзины" = v_корзина AND c."id_варианта" = v."id_варианта";

    INSERT INTO "Платёж" ("id_заказа", "способ", "сумма", "состояние", "id_операции")
    VALUES (v_заказ, p_оплата, v_товары + v_доставка,
            CASE WHEN p_оплата = 'card' THEN 'succeeded'::payment_state ELSE 'pending'::payment_state END,
            p_операция);
    INSERT INTO "Событие_заказа" ("id_заказа", "id_автора", "статус")
    VALUES (v_заказ, p_покупатель, 'new');
    INSERT INTO "Уведомление" ("id_пользователя", "id_заказа", "текст")
    VALUES (p_покупатель, v_заказ, format('Заказ %s принят. Сумма: %s ₽.', p_номер, v_товары + v_доставка));
    DELETE FROM "Позиция_корзины" WHERE "id_корзины" = v_корзина;
    RETURN v_заказ;
END;
$$;

CREATE FUNCTION подтвердить_оплату(p_заказ integer, p_сотрудник integer)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM "Сотрудник_магазина" s JOIN "Пользователь" u USING ("id_пользователя")
    WHERE s."id_пользователя" = p_сотрудник AND s."права_доступа" IN ('orders', 'manager')
      AND u."статус_аккаунта" = 'active';
    IF NOT FOUND THEN RAISE EXCEPTION 'Нет права подтверждать оплату'; END IF;
    PERFORM 1 FROM "Заказ" WHERE "id_заказа" = p_заказ AND "статус" <> 'cancelled' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Заказ отсутствует или отменён'; END IF;
    UPDATE "Платёж" SET "состояние" = 'succeeded', "дата_операции" = CURRENT_TIMESTAMP
    WHERE "id_заказа" = p_заказ AND "способ" = 'receipt' AND "состояние" = 'pending';
    IF NOT FOUND AND NOT EXISTS (
        SELECT 1 FROM "Платёж" WHERE "id_заказа" = p_заказ AND "состояние" = 'succeeded'
    ) THEN RAISE EXCEPTION 'Нет оплаты, ожидающей подтверждения'; END IF;
END;
$$;

CREATE FUNCTION изменить_статус_заказа(p_заказ integer, p_статус order_status, p_автор integer)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_заказ "Заказ"%ROWTYPE;
    v_сотрудник boolean;
    v_название text;
    v_строка record;
BEGIN
    SELECT * INTO v_заказ FROM "Заказ" WHERE "id_заказа" = p_заказ FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Заказ не найден'; END IF;
    SELECT EXISTS (
        SELECT 1 FROM "Сотрудник_магазина" s JOIN "Пользователь" u USING ("id_пользователя")
        WHERE s."id_пользователя" = p_автор AND s."права_доступа" IN ('orders', 'manager')
          AND u."статус_аккаунта" = 'active'
    ) INTO v_сотрудник;
    IF NOT v_сотрудник AND NOT (
        p_статус = 'cancelled' AND p_автор = v_заказ."id_покупателя" AND EXISTS (
            SELECT 1 FROM "Пользователь" WHERE "id_пользователя" = p_автор AND "статус_аккаунта" = 'active'
        )
    ) THEN RAISE EXCEPTION 'Нет права изменять этот заказ'; END IF;
    IF p_статус IS NULL THEN RAISE EXCEPTION 'Статус не указан'; END IF;
    IF p_статус = v_заказ."статус" THEN RETURN; END IF;
    IF NOT (
        (v_заказ."статус" = 'new' AND p_статус = 'confirmed') OR
        (v_заказ."статус" = 'confirmed' AND p_статус = 'packing') OR
        (v_заказ."статус" = 'packing' AND p_статус = 'shipped') OR
        (v_заказ."статус" = 'shipped' AND p_статус = 'delivered') OR
        (v_заказ."статус" IN ('new', 'confirmed', 'packing') AND p_статус = 'cancelled')
    ) THEN RAISE EXCEPTION 'Недопустимый переход статуса'; END IF;

    IF p_статус = 'delivered' AND NOT EXISTS (
        SELECT 1 FROM "Платёж" WHERE "id_заказа" = p_заказ
          AND "состояние" = 'succeeded' AND "сумма" = v_заказ."итоговая_сумма"
    ) THEN RAISE EXCEPTION 'Получение оплаты не подтверждено'; END IF;

    IF p_статус = 'cancelled' THEN
        FOR v_строка IN
            SELECT r."id_резерва", r."количество", i."id_варианта"
            FROM "Резерв" r JOIN "Позиция_заказа" i USING ("id_позиции_заказа")
            WHERE i."id_заказа" = p_заказ AND r."состояние" = 'active'
            ORDER BY i."id_варианта" FOR UPDATE OF r
        LOOP
            UPDATE "Вариант_товара" SET "доступный_остаток" = "доступный_остаток" + v_строка."количество"
            WHERE "id_варианта" = v_строка."id_варианта";
            UPDATE "Резерв" SET "состояние" = 'released' WHERE "id_резерва" = v_строка."id_резерва";
        END LOOP;
        UPDATE "Платёж" SET "состояние" = 'refund_pending'
        WHERE "id_заказа" = p_заказ AND "способ" = 'card' AND "состояние" = 'succeeded';
        UPDATE "Платёж" SET "состояние" = 'failed'
        WHERE "id_заказа" = p_заказ AND "состояние" = 'pending';
    ELSIF p_статус = 'shipped' THEN
        UPDATE "Резерв" r SET "состояние" = 'fulfilled'
        FROM "Позиция_заказа" i
        WHERE i."id_позиции_заказа" = r."id_позиции_заказа"
          AND i."id_заказа" = p_заказ AND r."состояние" = 'active';
    END IF;

    UPDATE "Заказ" SET "статус" = p_статус WHERE "id_заказа" = p_заказ;
    INSERT INTO "Событие_заказа" ("id_заказа", "id_автора", "статус") VALUES (p_заказ, p_автор, p_статус);
    v_название := CASE p_статус WHEN 'confirmed' THEN 'Подтверждён' WHEN 'packing' THEN 'Собирается'
        WHEN 'shipped' THEN 'Отправлен' WHEN 'delivered' THEN 'Доставлен' WHEN 'cancelled' THEN 'Отменён' ELSE 'Новый' END;
    INSERT INTO "Уведомление" ("id_пользователя", "id_заказа", "текст")
    VALUES (v_заказ."id_покупателя", p_заказ, format('Заказ %s: %s.', v_заказ."номер", v_название));
END;
$$;

