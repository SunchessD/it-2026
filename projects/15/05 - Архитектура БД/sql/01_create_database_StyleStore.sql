BEGIN;

CREATE SCHEMA stylestore;
SET search_path TO stylestore, public;

CREATE TYPE account_status AS ENUM ('inactive', 'active');

CREATE TYPE staff_access AS ENUM ('catalog', 'orders', 'manager');

CREATE TYPE token_purpose AS ENUM ('activation', 'password_reset');

CREATE TYPE order_status AS ENUM ('new', 'confirmed', 'packing', 'shipped', 'delivered', 'cancelled');

CREATE TYPE delivery_method AS ENUM ('courier', 'pickup');

CREATE TYPE payment_method AS ENUM ('card', 'receipt');

CREATE TYPE payment_state AS ENUM ('pending', 'succeeded', 'failed', 'refund_pending', 'refunded');

CREATE TYPE reserve_state AS ENUM ('active', 'released', 'fulfilled');

CREATE TABLE "Пользователь" (
  "id_пользователя" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "имя" varchar(255) NOT NULL CHECK (length(btrim("имя")) >= 2),
  "email" varchar(255) NOT NULL UNIQUE CHECK (position('@' IN "email") > 1),
  "хеш_пароля" varchar(255) NOT NULL,
  "статус_аккаунта" account_status NOT NULL DEFAULT 'inactive',
  "дата_регистрации" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "Покупатель" (
  "id_пользователя" integer PRIMARY KEY REFERENCES "Пользователь"("id_пользователя"),
  "телефон" varchar(32) NOT NULL DEFAULT '',
  "адрес_по_умолчанию" varchar(500) NOT NULL DEFAULT ''
);

CREATE TABLE "Сотрудник_магазина" (
  "id_пользователя" integer PRIMARY KEY REFERENCES "Пользователь"("id_пользователя"),
  "должность" varchar(100) NOT NULL,
  "права_доступа" staff_access NOT NULL
);

CREATE TABLE "Токен_аккаунта" (
  "хеш_токена" varchar(255) PRIMARY KEY,
  "id_пользователя" integer NOT NULL REFERENCES "Пользователь"("id_пользователя"),
  "назначение" token_purpose NOT NULL,
  "истекает_в" timestamp NOT NULL,
  "использован_в" timestamp
);

CREATE INDEX "ix_Токен_аккаунта_1" ON "Токен_аккаунта" ("id_пользователя", "назначение");

CREATE TABLE "Категория" (
  "id_категории" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "название" varchar(255) NOT NULL UNIQUE,
  "описание" text NOT NULL
);

CREATE TABLE "Товар" (
  "id_товара" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_категории" integer NOT NULL REFERENCES "Категория"("id_категории"),
  "артикул" varchar(64) NOT NULL UNIQUE,
  "название" varchar(255) NOT NULL,
  "описание" text NOT NULL,
  "фотография" varchar(2048) NOT NULL,
  "цена" numeric(12,2) NOT NULL,
  "прежняя_цена" numeric(12,2),
  "опубликован" boolean NOT NULL DEFAULT FALSE,
  CHECK ("цена" >= 0),
  CHECK ("прежняя_цена" IS NULL OR "прежняя_цена" > "цена")
