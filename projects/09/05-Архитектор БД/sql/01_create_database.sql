-- ReviewGuard: схема PostgreSQL 17.
-- Запускать в уже созданной базе от роли с правом создавать объекты в схеме.

CREATE SCHEMA IF NOT EXISTS reviewguard;
SET search_path TO reviewguard, public;

CREATE TABLE organization (
    organization_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(200) NOT NULL,
    data_revision    bigint NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT organization_name_check CHECK (name = btrim(name) AND char_length(name) > 0),
    CONSTRAINT organization_revision_check CHECK (data_revision >= 0)
);

CREATE TABLE account (
    account_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (organization_id) ON DELETE RESTRICT,
    full_name        varchar(200) NOT NULL,
    email            varchar(320) NOT NULL,
    password_hash    varchar(255) NOT NULL,
    role             varchar(32) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT account_name_check CHECK (full_name = btrim(full_name) AND char_length(full_name) > 0),
    CONSTRAINT account_email_check CHECK (email = btrim(email) AND position('@' IN email) > 1),
    CONSTRAINT account_role_check CHECK (role IN ('organization_admin', 'analyst'))
);
CREATE UNIQUE INDEX account_email_lower_uq ON account (lower(email));

CREATE TABLE invitation (
    invitation_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (organization_id) ON DELETE RESTRICT,
    code             varchar(64) NOT NULL UNIQUE,
    revoked          boolean NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT invitation_code_check CHECK (code = btrim(code) AND char_length(code) >= 20)
);
CREATE INDEX invitation_org_active_idx ON invitation (organization_id) WHERE NOT revoked;

CREATE TABLE monitored_object (
    object_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (organization_id) ON DELETE RESTRICT,
    name             varchar(200) NOT NULL,
    object_type      varchar(16) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT monitored_object_name_check CHECK (name = btrim(name) AND char_length(name) > 0),
    CONSTRAINT monitored_object_type_check CHECK (object_type IN ('product', 'service')),
    CONSTRAINT monitored_object_org_uq UNIQUE (object_id, organization_id)
);

CREATE TABLE source (
    source_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id        bigint NOT NULL,
    organization_id  bigint NOT NULL,
    platform_name    varchar(200) NOT NULL,
    card_url         varchar(2000) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT source_platform_check CHECK (platform_name = btrim(platform_name) AND char_length(platform_name) > 0),
    CONSTRAINT source_url_check CHECK (card_url LIKE 'https://%' AND card_url !~ '\s'),
    CONSTRAINT source_object_fk FOREIGN KEY (object_id, organization_id)
        REFERENCES monitored_object (object_id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT source_org_uq UNIQUE (source_id, organization_id),
    CONSTRAINT source_object_org_uq UNIQUE (source_id, organization_id, object_id)
);

CREATE TABLE anomaly_threshold (
    organization_id   bigint PRIMARY KEY REFERENCES organization (organization_id) ON DELETE RESTRICT,
    negativity_limit  numeric(8,2) NOT NULL,
    spam_limit        numeric(8,2) NOT NULL,
    version           bigint NOT NULL DEFAULT 0,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    updated_by        bigint NULL REFERENCES account (account_id) ON DELETE RESTRICT,
    CONSTRAINT anomaly_threshold_negativity_check CHECK (negativity_limit BETWEEN 1 AND 100),
    CONSTRAINT anomaly_threshold_spam_check CHECK (spam_limit BETWEEN 1 AND 100),
    CONSTRAINT anomaly_threshold_version_check CHECK (version >= 0)
);

CREATE TABLE import_batch (
    import_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id        bigint NOT NULL,
    organization_id  bigint NOT NULL,
    status           varchar(16) NOT NULL,
    accepted_count   integer NOT NULL,
    undated_count    integer NOT NULL,
    failure_reason   varchar(500) NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    started_at       timestamptz NULL,
    finished_at      timestamptz NULL,
    CONSTRAINT import_batch_status_check CHECK (status IN ('accepted', 'processing', 'ready', 'failed')),
    CONSTRAINT import_batch_counts_check CHECK (accepted_count >= 0 AND undated_count BETWEEN 0 AND accepted_count),
    CONSTRAINT import_batch_failure_check CHECK (
        (status = 'failed' AND failure_reason IS NOT NULL AND char_length(btrim(failure_reason)) > 0)
        OR (status <> 'failed' AND failure_reason IS NULL)
    ),
    CONSTRAINT import_batch_time_check CHECK (
        (status = 'accepted' AND started_at IS NULL AND finished_at IS NULL)
        OR (status = 'processing' AND started_at IS NOT NULL AND finished_at IS NULL)
        OR (status IN ('ready', 'failed') AND started_at IS NOT NULL AND finished_at IS NOT NULL AND started_at <= finished_at)
    ),
    CONSTRAINT import_batch_source_fk FOREIGN KEY (source_id, organization_id)
        REFERENCES source (source_id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT import_batch_identity_uq UNIQUE (import_id, organization_id, source_id)
);

CREATE TABLE review (
    review_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id        bigint NOT NULL,
    source_id        bigint NOT NULL,
    object_id        bigint NOT NULL,
    organization_id  bigint NOT NULL,
    body             text NOT NULL,
    reviewed_at      timestamptz NULL,
    sentiment        varchar(16) NULL,
    spam             boolean NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT review_body_check CHECK (char_length(btrim(body)) > 0),
    CONSTRAINT review_sentiment_check CHECK (sentiment IS NULL OR sentiment IN ('positive', 'neutral', 'negative')),
    CONSTRAINT review_spam_needs_date CHECK (spam IS NULL OR reviewed_at IS NOT NULL),
    CONSTRAINT review_import_fk FOREIGN KEY (import_id, organization_id, source_id)
        REFERENCES import_batch (import_id, organization_id, source_id) ON DELETE RESTRICT,
    CONSTRAINT review_source_fk FOREIGN KEY (source_id, organization_id, object_id)
        REFERENCES source (source_id, organization_id, object_id) ON DELETE RESTRICT,
    CONSTRAINT review_identity_uq UNIQUE (review_id, organization_id, object_id)
);
CREATE INDEX review_dashboard_idx ON review (organization_id, object_id, reviewed_at) WHERE sentiment IS NOT NULL;
CREATE INDEX review_feed_idx ON review (organization_id, source_id, sentiment, reviewed_at DESC, review_id DESC);
CREATE INDEX review_object_time_idx ON review (object_id, reviewed_at) WHERE reviewed_at IS NOT NULL;

CREATE TABLE anomaly (
    anomaly_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id        bigint NOT NULL,
    organization_id  bigint NOT NULL,
    anomaly_type     varchar(16) NOT NULL,
    status           varchar(16) NOT NULL DEFAULT 'open',
    window_start     timestamptz NOT NULL,
    window_end       timestamptz NOT NULL,
    baseline_start   timestamptz NOT NULL,
    baseline_end     timestamptz NOT NULL,
    window_total     integer NOT NULL,
    window_marked    integer NOT NULL,
    baseline_total   integer NOT NULL,
    baseline_marked  integer NOT NULL,
    window_rate      numeric(8,6) NOT NULL,
    baseline_rate    numeric(8,6) NOT NULL,
    version          bigint NOT NULL DEFAULT 0,
    opened_at        timestamptz NOT NULL DEFAULT now(),
    resolved_at      timestamptz NULL,
    resolved_by      bigint NULL REFERENCES account (account_id) ON DELETE RESTRICT,
    CONSTRAINT anomaly_type_check CHECK (anomaly_type IN ('negativity', 'spam')),
    CONSTRAINT anomaly_status_check CHECK (status IN ('open', 'confirmed', 'false_positive')),
    CONSTRAINT anomaly_window_check CHECK (window_start < window_end),
    CONSTRAINT anomaly_baseline_check CHECK (baseline_start < baseline_end AND baseline_end = window_start),
    CONSTRAINT anomaly_window_counts_check CHECK (window_total >= 5 AND window_marked BETWEEN 0 AND window_total),
    CONSTRAINT anomaly_baseline_counts_check CHECK (baseline_total >= 5 AND baseline_marked BETWEEN 0 AND baseline_total),
    CONSTRAINT anomaly_rate_check CHECK (window_rate BETWEEN 0 AND 1 AND baseline_rate BETWEEN 0 AND 1),
    CONSTRAINT anomaly_version_check CHECK (version >= 0),
    CONSTRAINT anomaly_resolution_check CHECK (
        (status = 'open' AND resolved_at IS NULL AND resolved_by IS NULL)
        OR (status <> 'open' AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL)
    ),
    CONSTRAINT anomaly_object_fk FOREIGN KEY (object_id, organization_id)
        REFERENCES monitored_object (object_id, organization_id) ON DELETE RESTRICT,
    CONSTRAINT anomaly_org_uq UNIQUE (anomaly_id, organization_id),
    CONSTRAINT anomaly_identity_uq UNIQUE (anomaly_id, organization_id, object_id),
    CONSTRAINT anomaly_window_uq UNIQUE (object_id, anomaly_type, window_start, window_end)
);
CREATE INDEX anomaly_org_idx ON anomaly (organization_id, opened_at DESC, anomaly_id DESC);

CREATE TABLE anomaly_review (
    anomaly_id       bigint NOT NULL,
    review_id        bigint NOT NULL,
    organization_id  bigint NOT NULL,
    object_id        bigint NOT NULL,
    PRIMARY KEY (anomaly_id, review_id),
    CONSTRAINT anomaly_review_anomaly_fk FOREIGN KEY (anomaly_id, organization_id, object_id)
        REFERENCES anomaly (anomaly_id, organization_id, object_id) ON DELETE RESTRICT,
    CONSTRAINT anomaly_review_review_fk FOREIGN KEY (review_id, organization_id, object_id)
        REFERENCES review (review_id, organization_id, object_id) ON DELETE RESTRICT
);

CREATE TABLE notification (
    notification_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anomaly_id       bigint NOT NULL,
    organization_id  bigint NOT NULL,
    message          varchar(500) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT notification_message_check CHECK (message = btrim(message) AND char_length(message) > 0),
    CONSTRAINT notification_anomaly_fk FOREIGN KEY (anomaly_id, organization_id)
        REFERENCES anomaly (anomaly_id, organization_id) ON DELETE RESTRICT
);
CREATE INDEX notification_org_idx ON notification (organization_id, created_at DESC);
