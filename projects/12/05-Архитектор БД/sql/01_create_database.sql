-- RoomBook: схема PostgreSQL 14+
-- Запускать в целевой базе данных от роли, имеющей право CREATE EXTENSION.

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA IF NOT EXISTS roombook;
SET search_path TO roombook, public;

CREATE TABLE users (
    user_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            varchar(320) NOT NULL,
    full_name        varchar(200) NOT NULL,
    role             varchar(20) NOT NULL,
    is_active        boolean NOT NULL DEFAULT true,
    password_hash    varchar(255) NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_role_check CHECK (role IN ('student', 'teacher', 'dispatcher'))
);
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));

CREATE TABLE buildings (
    building_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(120) NOT NULL UNIQUE,
    address          text NOT NULL,
    opens_at         time NOT NULL,
    closes_at        time NOT NULL,
    CONSTRAINT buildings_hours_check CHECK (opens_at < closes_at)
);

CREATE TABLE rooms (
    room_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id      bigint NOT NULL REFERENCES buildings(building_id) ON DELETE RESTRICT,
    room_number      varchar(30) NOT NULL,
    capacity         integer NOT NULL,
    is_bookable      boolean NOT NULL DEFAULT true,
    CONSTRAINT rooms_building_number_uq UNIQUE (building_id, room_number),
    CONSTRAINT rooms_capacity_check CHECK (capacity > 0)
);

CREATE TABLE equipment (
    equipment_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(100) NOT NULL UNIQUE
);

CREATE TABLE room_equipment (
    room_id          bigint NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    equipment_id     bigint NOT NULL REFERENCES equipment(equipment_id) ON DELETE RESTRICT,
    quantity         integer NOT NULL DEFAULT 1,
    PRIMARY KEY (room_id, equipment_id),
    CONSTRAINT room_equipment_quantity_check CHECK (quantity > 0)
);

CREATE TABLE schedule_entries (
    schedule_entry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id           bigint NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    teacher_id        bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    weekday           smallint NOT NULL,
    discipline        varchar(200) NOT NULL,
    study_group       varchar(80) NOT NULL,
    valid_from        date NOT NULL,
    valid_until       date NOT NULL,
    starts_at         time NOT NULL,
    ends_at           time NOT NULL,
    CONSTRAINT schedule_weekday_check CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT schedule_dates_check CHECK (valid_from <= valid_until),
    CONSTRAINT schedule_time_check CHECK (starts_at < ends_at)
);

CREATE TABLE bookings (
    booking_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id           bigint NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    author_id         bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    booking_date      date NOT NULL,
    starts_at         time NOT NULL,
    ends_at           time NOT NULL,
    booking_slot      tsrange GENERATED ALWAYS AS (
        tsrange(booking_date + starts_at, booking_date + ends_at, '[)')
    ) STORED,
    purpose           varchar(500) NOT NULL,
    participant_count integer NOT NULL,
    status            varchar(24) NOT NULL DEFAULT 'pending',
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT bookings_time_check CHECK (starts_at < ends_at),
    CONSTRAINT bookings_participants_check CHECK (participant_count > 0),
    CONSTRAINT bookings_status_check CHECK (
        status IN ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')
    ),
    CONSTRAINT bookings_no_confirmed_overlap
        EXCLUDE USING gist (room_id WITH =, booking_slot WITH &&)
        WHERE (status = 'confirmed')
);

CREATE TABLE booking_status_history (
    history_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       bigint NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    changed_by       bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    old_status       varchar(24),
    new_status       varchar(24) NOT NULL,
    reason           text,
    changed_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT history_old_status_check CHECK (
        old_status IS NULL OR old_status IN ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')
    ),
    CONSTRAINT history_new_status_check CHECK (
        new_status IN ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')
    )
);

CREATE TABLE notifications (
    notification_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id     bigint NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    booking_id       bigint REFERENCES bookings(booking_id) ON DELETE SET NULL,
    message          text NOT NULL,
    is_read          boolean NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX rooms_building_idx ON rooms (building_id, room_number);
CREATE INDEX schedule_room_weekday_dates_idx
    ON schedule_entries (room_id, weekday, valid_from, valid_until);
CREATE INDEX bookings_author_created_idx ON bookings (author_id, created_at DESC);
CREATE INDEX booking_history_booking_changed_idx
    ON booking_status_history (booking_id, changed_at DESC);
CREATE INDEX notifications_recipient_read_created_idx
    ON notifications (recipient_id, is_read, created_at DESC);

-- Правила, зависящие от нескольких таблиц, проверяются перед записью брони.
CREATE FUNCTION validate_booking() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    room_capacity integer;
    room_is_bookable boolean;
    building_opens time;
    building_closes time;
    schedule_conflict boolean;
BEGIN
    SELECT r.capacity, r.is_bookable, b.opens_at, b.closes_at
      INTO room_capacity, room_is_bookable, building_opens, building_closes
      FROM rooms r
      JOIN buildings b ON b.building_id = r.building_id
     WHERE r.room_id = NEW.room_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Room % does not exist', NEW.room_id;
    END IF;
    IF NEW.status IN ('pending', 'confirmed') THEN
        IF NOT room_is_bookable THEN
            RAISE EXCEPTION 'Room % is not available for booking', NEW.room_id;
        END IF;
        IF NEW.participant_count > room_capacity THEN
            RAISE EXCEPTION 'Participant count % exceeds room capacity %',
                NEW.participant_count, room_capacity;
        END IF;
        IF NEW.starts_at < building_opens OR NEW.ends_at > building_closes THEN
            RAISE EXCEPTION 'Booking time must be within building opening hours';
        END IF;
    END IF;

    IF NEW.status = 'confirmed' THEN
        SELECT EXISTS (
            SELECT 1
              FROM schedule_entries s
             WHERE s.room_id = NEW.room_id
               AND s.weekday = extract(isodow FROM NEW.booking_date)::smallint
               AND NEW.booking_date BETWEEN s.valid_from AND s.valid_until
               AND s.starts_at < NEW.ends_at
               AND s.ends_at > NEW.starts_at
        ) INTO schedule_conflict;

        IF schedule_conflict THEN
            RAISE EXCEPTION 'Booking conflicts with the regular schedule';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER bookings_validate_before_write
BEFORE INSERT OR UPDATE OF room_id, booking_date, starts_at, ends_at, participant_count, status
ON bookings
FOR EACH ROW EXECUTE FUNCTION validate_booking();

-- Статусы в БД: pending = «На рассмотрении»; confirmed = «Подтверждено»;
-- rejected = «Отклонено»; cancelled = «Отменено»; completed = «Завершено».
